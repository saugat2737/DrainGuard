import { Zone, ZoneRisk, Report } from "./types";
import { ScoredRoute } from "./routing";

export interface WhatsAppAlertOptions {
  zone: Zone;
  risk: ZoneRisk;
  alternativeRoute?: ScoredRoute | null;
  appUrl?: string;
}

export interface MunicipalDispatchOrderOptions {
  zone: Zone;
  risk: ZoneRisk;
  reports: Report[];
  firstHighHour?: string | null;
  actBy?: string | null;
}

/**
 * Generate a prefilled WhatsApp alert link for citizens.
 * Format:
 * ⚠️ DrainGuard Waterlogging Alert — [Zone Name]
 * Risk Level: [HIGH/SEVERE/MODERATE] ([Score]/100)
 * Contributing Factors: [Summary of top factors]
 * Recommended Action: [Avoid corridor / Use alternative]
 * [Alternative route details if provided]
 * View live evidence: [App URL]
 */
export function generateWhatsAppAlertText(options: WhatsAppAlertOptions): string {
  const { zone, risk, alternativeRoute, appUrl = "https://drainguard.in" } = options;
  const levelUpper = risk.level.toUpperCase();

  const lines: string[] = [
    `⚠️ *DrainGuard Waterlogging Alert — ${zone.name}*`,
    `*Risk Level:* ${levelUpper} (${risk.score}/100)`,
    `*Primary Cause:* ${risk.explanation || "Elevated surface water accumulation risk."}`,
  ];

  if (alternativeRoute) {
    const extraMinutes = Math.round((alternativeRoute.delay_vs_fastest_s || 0) / 60);
    lines.push(
      `*Alternative Recommended:* ${alternativeRoute.preference || "Safer"} corridor (adds ~${extraMinutes}m, avoids high hazard choke point).`
    );
  } else {
    lines.push(
      risk.score >= 50
        ? `*Recommendation:* Avoid low-lying underpasses and arterial crossings in this zone if commuting during heavy rain.`
        : `*Recommendation:* Exercise standard caution along this corridor.`
    );
  }

  lines.push(`🔍 *Live Evidence & Basin Map:* ${appUrl}`);
  return lines.join("\n\n");
}

/**
 * Return encoded wa.me URL for one-click WhatsApp sharing.
 */
export function generateWhatsAppShareUrl(options: WhatsAppAlertOptions): string {
  const text = generateWhatsAppAlertText(options);
  return `https://wa.me/?text=${encodeURIComponent(text)}`;
}

/**
 * Generate structured municipal dispatch order for clearing crews.
 * Suitable for instant clipboard copy and SMS/radio transmission.
 */
export function generateMunicipalDispatchOrder(options: MunicipalDispatchOrderOptions): string {
  const { zone, risk, reports, firstHighHour, actBy } = options;
  const openReports = reports.filter((r) => r.status === "open" && (!r.zone_id || r.zone_id === zone.id));

  const lines: string[] = [
    `=== MUNICIPAL DRAINAGE DISPATCH ORDER ===`,
    `Target Zone: ${zone.name} (${zone.id})`,
    `Grounding Basis: ${zone.basis ? zone.basis.replace(/_/g, " ") : "Municipal Ward Corridor"}`,
    `Calculated Exposure: ${risk.score}/100 [${risk.level.toUpperCase()}]`,
    `Open Citizen Reports: ${openReports.length}`,
  ];

  if (firstHighHour && actBy) {
    lines.push(
      `Operational Clearance Window:`,
      `- High Risk Threshold Expected: ${firstHighHour}`,
      `- CLEARANCE DEADLINE (Act-By): ${actBy} (2h safety clearance window)`
    );
  } else if (firstHighHour) {
    lines.push(`- High Risk Threshold Forecast: ${firstHighHour}`);
  }

  lines.push(`Primary Hydrological Factors:`);
  risk.factors.forEach((f) => {
    lines.push(` - ${f.key.toUpperCase()} (${Math.round(f.weight * 100)}%): ${f.text} [${f.contribution.toFixed(1)} pts]`);
  });

  if (openReports.length > 0) {
    lines.push(`Debris & Choke Point Inspection Backlog:`);
    openReports.slice(0, 5).forEach((rep, idx) => {
      lines.push(
        ` [${idx + 1}] ID: ${rep.id} | Severity: ${rep.severity}/3 | Type: ${rep.blockage_type.toUpperCase()} | Loc: ${rep.lat.toFixed(4)}, ${rep.lng.toFixed(4)} | Note: ${rep.summary}`
      );
    });
    if (openReports.length > 5) {
      lines.push(` ...and ${openReports.length - 5} more report(s) in backlog.`);
    }
  } else {
    lines.push(`No unverified citizen reports pending. Pre-emptive desilting recommended.`);
  }

  lines.push(`Dispatch Generated by DrainGuard Intelligence System: ${new Date().toISOString()}`);
  return lines.join("\n");
}
